#!/usr/bin/env python3
"""Prepare the official RNNoise 0.2 source and its matching built-in model."""

import argparse
import hashlib
import io
from pathlib import Path
import shutil
import subprocess
import tarfile
import tempfile
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
VERSION = "0.2"
SOURCE_SHA256 = "e4a17eb1493b7551f9f7781d2acc67b8847d6ed7c4b64db0fd62c017021ae1ec"
MODEL_VERSION = "0b50c45"
MODEL_SHA256 = "4ac81c5c0884ec4bd5907026aaae16209b7b76cd9d7f71af582094a2f98f4b43"
SOURCES = ["denoise.c", "rnn.c", "pitch.c", "kiss_fft.c", "celt_lpc.c",
           "nnet.c", "nnet_default.c", "parse_lpcnet_weights.c",
           "rnnoise_data.c", "rnnoise_tables.c"]


def fetch(name, url, checksum):
    cache = ROOT / ".build/downloads"
    cache.mkdir(parents=True, exist_ok=True)
    path = cache / name
    if not path.exists():
        with urllib.request.urlopen(url, timeout=90) as response:
            data = response.read()
        if hashlib.sha256(data).hexdigest() != checksum:
            raise SystemExit(f"{name}: checksum mismatch")
        path.write_bytes(data)
    data = path.read_bytes()
    if hashlib.sha256(data).hexdigest() != checksum:
        raise SystemExit(f"{name}: checksum mismatch; remove the cached archive and retry")
    return data


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=ROOT / f"Client/apple/Vendor/rnnoise-{VERSION}")
    args = parser.parse_args()
    source = fetch(f"rnnoise-{VERSION}-source.tar.gz",
                   f"https://codeload.github.com/xiph/rnnoise/tar.gz/refs/tags/v{VERSION}", SOURCE_SHA256)
    model = fetch(f"rnnoise_data-{MODEL_VERSION}.tar.gz",
                  f"https://media.xiph.org/rnnoise/models/rnnoise_data-{MODEL_VERSION}.tar.gz", MODEL_SHA256)
    staging = Path(tempfile.mkdtemp(prefix="rnnoise-package-", dir=ROOT / ".build"))
    with tarfile.open(fileobj=io.BytesIO(source), mode="r:gz") as archive:
        archive.extractall(staging, filter="data")
    upstream = staging / f"rnnoise-{VERSION}"
    if (upstream / "model_version").read_text().strip() != MODEL_VERSION:
        raise SystemExit("RNNoise source and model versions do not match")
    boundary_patch = ROOT / "Client/apple/Patches/rnnoise-model-loading.patch"
    if shutil.which("patch"):
        subprocess.run(["patch", "--batch", "--forward", "-p1", "--fuzz=0", "--input",
                        str(boundary_patch)], cwd=upstream, check=True)
    else:
        # Git for Windows is already required by the client toolchain, while a
        # standalone GNU patch executable may not be on its native PATH.
        subprocess.run(["git", "init", "--quiet"], cwd=upstream, check=True)
        subprocess.run(["git", "apply", "--no-index", "--whitespace=error", "-"],
                       input=boundary_patch.read_bytes().replace(b"\r\n", b"\n"), cwd=upstream, check=True)
    with tarfile.open(fileobj=io.BytesIO(model), mode="r:gz") as archive:
        for name in ["src/rnnoise_data.c", "src/rnnoise_data.h"]:
            member = archive.extractfile(name)
            if member is None:
                raise SystemExit(f"Missing {name} in model archive")
            (upstream / name).write_bytes(member.read())
    package = staging / "package"
    implementation = package / "Sources/CRNNoise"
    headers = implementation / "include"
    headers.mkdir(parents=True)
    shutil.copy2(upstream / "include/rnnoise.h", headers)
    for name in SOURCES:
        shutil.copy2(upstream / "src" / name, implementation)
    for path in (upstream / "src").rglob("*.h"):
        target = implementation / path.relative_to(upstream / "src")
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(path, target)
    shutil.copy2(ROOT / "Client/apple/Patches/rnnoise-0.2-apple/os_support.h", implementation)
    shutil.copy2(upstream / "COPYING", package / "COPYING")
    source_list = ", ".join(f'"{name}"' for name in SOURCES)
    (package / "Package.swift").write_text(f'''// swift-tools-version: 6.4
// Generated by scripts/prepare-rnnoise.py with the pinned model and Apple header shim.
import PackageDescription
let package = Package(
    name: "RNNoise",
    platforms: [.macOS("27.0"), .iOS("27.0")],
    products: [.library(name: "RNNoise", targets: ["CRNNoise"])],
    targets: [.target(name: "CRNNoise", sources: [{source_list}],
                      publicHeadersPath: "include",
                      cSettings: [.define("RNNOISE_BUILD"), .define("DISABLE_DEBUG_FLOAT", to: "1")])]
)
''')
    destination = args.output.resolve()
    destination.parent.mkdir(parents=True, exist_ok=True)
    if destination.exists():
        shutil.rmtree(destination)
    shutil.move(str(package), destination)
    shutil.rmtree(staging)
    print(f"Prepared RNNoise {VERSION}, official full model {MODEL_VERSION} (SHA-256 verified)")


if __name__ == "__main__":
    main()
